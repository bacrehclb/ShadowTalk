#!/usr/bin/env python3
"""Collect upstream license texts for the release targets without editing sources."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from package import NOTICES, ROOT, TARGETS

NOTICE_NAME = re.compile(r"(?:licen[cs]e|copying|notice|copyright|patents)(?:[._-].*)?", re.I)
LICENSE_NAME = re.compile(r"(?:licen[cs]e|copying)(?:[._-].*)?", re.I)
# This file is a URL for an upstream logo, not code shipped in our binaries.
EXCLUDED = {"modernc.org/memory": {"LICENSE-LOGO"}}


def json_stream(data):
    decoder = json.JSONDecoder()
    position = 0
    while position < len(data):
        if data[position].isspace():
            position += 1
            continue
        item, position = decoder.raw_decode(data, position)
        yield item


def go(root, env, *args):
    return subprocess.check_output(
        ["go", *args], cwd=root, env=env, text=True, encoding="utf-8",
        stderr=subprocess.PIPE, timeout=180)


def collect(packages, modules, standard):
    for item in packages:
        if item.get("Standard"):
            standard.add(Path(item["Dir"]))
            continue
        module = item.get("Module")
        if not module:
            raise ValueError(f"cannot identify module for {item['ImportPath']}")
        if module.get("Main"):
            continue
        if module.get("Replace"):
            raise ValueError(f"review notices for replaced module: {module['Path']}")
        name, version, root = module["Path"], module["Version"], Path(module["Dir"])
        entry = modules.setdefault(name, dict(version=version, root=root, packages=set()))
        if (entry["version"], entry["root"]) != (version, root):
            raise ValueError(f"inconsistent module across release targets: {name}")
        entry["packages"].add(Path(item["Dir"]))


def license_paths(root, directories, excluded=()):
    """Include root and nested package notices, without walking unused test trees."""
    root = root.resolve()
    parents = {root}
    for directory in directories:
        directory = directory.resolve()
        if not directory.is_relative_to(root):
            raise ValueError(f"package outside its source root: {directory}")
        while directory != root:
            parents.add(directory)
            directory = directory.parent
    files = set()
    for directory in parents:
        for path in directory.iterdir():
            if path.is_file() and NOTICE_NAME.fullmatch(path.name):
                if not path.resolve().is_relative_to(root):
                    raise ValueError(f"notice outside its source root: {path}")
                name = path.relative_to(root).as_posix()
                if name not in excluded:
                    files.add(name)
    if not any(LICENSE_NAME.fullmatch(Path(name).name) for name in files):
        raise ValueError(f"no license text found in {root}; review this dependency")
    return sorted(files)


def section(title, root, files):
    result = [f"\n{'=' * 72}\n{title}\n".encode()]
    for name in files:
        data = (root / name).read_bytes()
        if not data.strip():
            raise ValueError(f"empty upstream notice: {root / name}")
        data.decode("utf-8")  # Fail visibly rather than silently corrupting a text.
        result += [f"\n--- {name} ---\n\n".encode(), data, b"\n"]
    return b"".join(result)


def generate(root):
    # Match GoReleaser's pure-Go build matrix, not tests or the entire go.mod graph.
    env = dict(os.environ, CGO_ENABLED="0", GOWORK="off", GOFLAGS="")
    toolchain = json.loads(go(root, env, "env", "-json", "GOROOT", "GOVERSION"))
    modules, standard = {}, set()
    for goos, goarch in TARGETS:
        data = go(root, dict(env, GOOS=goos, GOARCH=goarch),
                  "list", "-mod=readonly", "-deps", "-json", "./cmd/shadowtalk")
        collect(json_stream(data), modules, standard)
    if not modules or not standard:
        raise ValueError("empty dependency inventory")
    result = [(
        "ShadowTalk third-party notices\n"
        "Generated by packaging/notices.py from the runtime dependency graph.\n"
        "Targets: " + ", ".join(f"{goos}/{arch}" for goos, arch in TARGETS) + "\n"
        "Go toolchain: " + toolchain["GOVERSION"] + "\n\n"
        "Original upstream license and patent notices follow. This file is the\n"
        "union for all release targets; not every module is used on every OS.\n"
        "Upstream notice documents may also describe unlinked components.\n"
        "Tor and Lyrebird executables are separate downloads, not bundled here.\n"
        "ShadowTalk's own license is in the accompanying LICENSE file.\n"
    ).encode()]
    goroot = Path(toolchain["GOROOT"])
    result.append(section("Go runtime, standard library and vendored components",
                          goroot, license_paths(goroot, standard)))
    for name, entry in sorted(modules.items()):
        result.append(section(
            f"Module: {name}@{entry['version']}\nSource: https://pkg.go.dev/{name}@{entry['version']}",
            entry["root"], license_paths(entry["root"], entry["packages"], EXCLUDED.get(name, ())),
        ))
    # Generated Unicode tables refer to upstream terms rather than shipping a
    # separate license file. Keep the reviewed text locally for offline builds.
    result.append(section("Unicode data used by terminal text processing\n"
                          "Source: https://www.unicode.org/license.txt",
                          root / "packaging/licenses", ["Unicode-3.0.txt"]))
    return b"".join(result)


def write_atomic(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".notices-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(data)
        temporary.chmod(0o644)
        temporary.replace(path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    # Global before hooks run before GoReleaser requires an empty dist directory.
    parser.add_argument("--output", type=Path, default=ROOT / "bin/notices" / NOTICES)
    args = parser.parse_args()
    try:
        data = generate(ROOT)
        write_atomic(args.output, data)
    except subprocess.CalledProcessError as error:
        parser.exit(1, f"notices: go command failed\n{error.stderr}")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, f"notices: {error}\n")
    print(f"Wrote {args.output} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
